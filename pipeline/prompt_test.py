"""
prompt_test.py
Compare YOLOE detection quality across prompts generated by different LLMs.

Loads prompt banks from:
    datasets/prompt/<dataset>/<object_folder>.json

Measures per prompt:  YOLOE confidence, mask size, IoU vs GT mask.
Ranks LLMs by:        detection rate, mean confidence, best confidence.

Usage:
    # Test all DexYCB objects using pre-generated prompt banks
    python pipeline/prompt_test.py --dataset dexycb

    # Test one object only
    python pipeline/prompt_test.py --dataset dexycb --obj 006_mustard_bottle

    # Auto-generate LLaMA prompt banks first (calls Ollama), then test
    python pipeline/prompt_test.py --dataset dexycb --generate llama

    # Generate + test all at once
    python pipeline/prompt_test.py --dataset dexycb --generate llama --run
"""

